#!/usr/bin/env node
// Builds benchmark/index.html from data/leaderboard.json: the static page (board B "instrument") with every row
// rendered, the data inlined for sort, filter and expand, and a copy of the data file beside it for download.
// node scripts/build-benchmark.mjs [--data data/leaderboard.json] [--out benchmark] [--check]
//   --check  writes nothing; exits 1 if the committed page differs from what the data builds.
// A row missing a field the page shows exits 1 and writes nothing (the contract: no row ships without its source).
import fs from 'node:fs'; import path from 'node:path'; import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { nav, footer, SHELL_CSS } from './bench/shell.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url)), ROOT = path.resolve(HERE, '..');
const argv = process.argv.slice(2), arg = (k, d) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : d; };
const DATA_FILE = path.resolve(ROOT, arg('--data', 'data/leaderboard.json'));
const OUT = path.resolve(ROOT, arg('--out', 'benchmark'));
const CHECK = argv.includes('--check');
const die = (msg) => { process.stderr.write(`build-benchmark: ${msg}\n`); process.exit(1); };

// ---------- the contract ----------
const raw = fs.readFileSync(DATA_FILE, 'utf8');
let DATA; try { DATA = JSON.parse(raw); } catch (e) { die(`${DATA_FILE} is not JSON: ${e.message}`); }
const TEXT = ['id', 'system', 'model', 'vendor', 'measured_by', 'version', 'judge', 'source', 'read', 'judge_logs'];
const NUM = ['f1', 'precision', 'recall', 'instances', 'notes', 'comments'];
const errs = [];
if (!Array.isArray(DATA.rows) || !DATA.rows.length) errs.push('no rows');
const seen = new Set();
for (const [i, r] of (DATA.rows || []).entries()) {
  const at = r.id || `rows[${i}]`;
  for (const k of TEXT) if (typeof r[k] !== 'string' || !r[k].trim()) errs.push(`${at}: ${k} missing`);
  for (const k of NUM) if (typeof r[k] !== 'number' || !Number.isFinite(r[k])) errs.push(`${at}: ${k} not a number`);
  for (const k of ['f1', 'precision', 'recall']) if (r[k] < 0 || r[k] > 100) errs.push(`${at}: ${k} outside 0 to 100`);
  if (r.read && !/^\d{4}-\d{2}-\d{2}$/.test(r.read)) errs.push(`${at}: read is not a date`);
  if (r.judge_logs === 'available' && !(r.rounds > 0)) errs.push(`${at}: judge logs available but no rounds`);
  if (seen.has(r.id)) errs.push(`${at}: duplicate id`); seen.add(r.id);
}
for (const k of ['benchmark', 'columns', 'escaped_defects', 'unscored']) if (!DATA[k]) errs.push(`${k} missing`);
if (!(DATA.rows || []).some((r) => r.measured_by === 'Measured by us')) errs.push('no row measured by us');
if (errs.length) die(`${path.relative(ROOT, DATA_FILE)}: ${errs.join('; ')}`);

// ---------- judge logs: linked only when the files are on the site (benchmark/logs/<id>/round-<n>.json) ----------
const logs = {};
for (const r of DATA.rows) {
  if (r.judge_logs !== 'available') continue;
  const files = Array.from({ length: r.rounds }, (_, j) => `logs/${r.id}/round-${j + 1}.json`).filter((f) => fs.existsSync(path.join(OUT, f)));
  if (files.length) logs[r.id] = files.map((f) => ({ name: f.slice(5), href: f }));
}
const OPT = { logs, paper: '../paper/' };

// ---------- render: the same view code the browser runs ----------
const VIEW = fs.readFileSync(path.join(HERE, 'bench/view.js'), 'utf8');
const CLIENT = fs.readFileSync(path.join(HERE, 'bench/client.js'), 'utf8');
const CSS = fs.readFileSync(path.join(HERE, 'bench/page.css'), 'utf8');
const ctx = vm.createContext({}); vm.runInContext(VIEW, ctx);
const V = ctx.benchView(DATA, OPT), st = V.newState();
const json = (o) => JSON.stringify(o).replace(/</g, '\\u003c');
const strip = (s) => s.replace(/^\s*\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\n\s*\n/g, '\n');
const best = V.view(st)[0].r;

const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Benchmark · provedreview</title>
<meta name="description" content="AACR-Bench leaderboard: ${DATA.rows.length} rows, who measured each, on which version, over how many instances, with which judge. ${best.system} ${best.f1} F1.">
<!-- generated by scripts/build-benchmark.mjs from data/leaderboard.json; do not edit by hand -->
<style>
${strip(CSS).trim()}
${SHELL_CSS.trim()}
:root{--step:${V.STEP}}
</style>
</head>
<body>
${nav({ base: '../', cur: 'Benchmark' })}
<main class="wrap">
${V.pheadHtml()}
<div class="barh">${V.barHtml(st, null)}</div>
<div class="scr"><div class="tbl">${V.headHtml(st)}${V.bodyHtml(st, null)}</div></div>
<div class="tfoot">${V.tfootHtml(null)}</div>
${V.afterHtml()}
</main>
${footer({ base: '../' })}
<script type="application/json" id="lb-data">${json(DATA)}</script>
<script type="application/json" id="lb-opt">${json(OPT)}</script>
<script>
${VIEW.trim()}
${CLIENT.trim()}
</script>
</body>
</html>
`;

const outPage = path.join(OUT, 'index.html'), outData = path.join(OUT, 'leaderboard.json');
if (CHECK) {
  const stale = [[outPage, page], [outData, raw]].filter(([f, s]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== s).map(([f]) => path.relative(ROOT, f));
  if (stale.length) die(`stale, run node scripts/build-benchmark.mjs: ${stale.join(', ')}`);
  console.log(`build-benchmark: current (${DATA.rows.length} rows)`);
} else {
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(outPage, page); fs.writeFileSync(outData, raw);
  console.log(`build-benchmark: ${path.relative(ROOT, outPage)} (${DATA.rows.length} rows, ${(Buffer.byteLength(page) / 1024).toFixed(1)} KB), ${path.relative(ROOT, outData)}`);
}
